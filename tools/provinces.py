# سياق اتحادي/سياسي: «بغداد» هنا تعني الحكومة الاتحادية لا المحافظة
SKIP = ["بغداد وأربيل", "بغداد واربيل", "أربيل وبغداد", "اربيل وبغداد", "بين بغداد", "حكومة بغداد", "بغداد و أربيل", "أربيل و بغداد",
        "صلاح الدين الأيوبي", "جامعة الكوفة في", "ملعب البصرة الدولي"]

_L = "ء-يٱ-ۓچگ"


def norm(s):
    s = re.sub("[ً-ْـ]", "", s or "")
    return s.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا").replace("ة", "ه").replace("ى", "ي")


def _variants(term):
    t = norm(term)
    out = [t]
    if t.startswith("ال") and len(t) > 3:
        out.append("لل" + t[2:])  # للبصرة، للموصل
    return out


_RX = {g: re.compile(r"(?<![" + _L + r"])(?:[وبف]|وب|ول|فب)?(?:" + "|".join(sorted({re.escape(v) for t in ts for v in _variants(t)}, key=len, reverse=True))
                     + r")(?![" + _L + r"])") for g, ts in GOVS.items()}
_SKIP_RX = re.compile("|".join(re.escape(norm(s)) for s in SKIP))


def _prep(text):
    return _SKIP_RX.sub(lambda m: " " * len(m.group(0)), norm(text))


def provinces_in(text):
    """كل المحافظات المذكورة بالنص مرتبة حسب أول ظهور."""
    t = _prep(text)
    hits = []
    for g, rx in _RX.items():
        m = rx.search(t)
        if m:
            hits.append((m.start(), -(m.end() - m.start()), g))
    return [g for _, _, g in sorted(hits)]


def province_of(title):
    """أول محافظة تظهر بالعنوان، أو None."""
    p = provinces_in(title)
    return p[0] if p else None


def mentions(text, gov):
    return gov in provinces_in(text)


