    tests = [("‏ بارزاني يفتتح طريق (كوري – شقلاوة – قنديل)", "بارزاني يفتتح طريق (كوري – شقلاوة – قنديل)"),
             ("اي_نيوز صحيفة بلجيكية: طائرة ركاب تهبط في مطار بروكسل", "صحيفة بلجيكية: طائرة ركاب تهبط في مطار بروكسل"),
             ("محافظة واسط تتصدر العراقق اخر 24 ساعة بهطول ألامطار", "محافظة واسط تتصدر العراق آخر 24 ساعة بهطول الأمطار"),
             ("أمانة بغداد تنجز ملعبين رياضييين في الصدر والشعلة", "أمانة بغداد تنجز ملعبين رياضيين في الصدر والشعلة"),
             ("معالي وزير التخطيط يبحثٌ مع محافظ الديوانية الواقع الخِدمي", "معالي وزير التخطيط يبحث مع محافظ الديوانية الواقع الخدمي"),
             ("اليوم … العراق والسعودية في نهائي كأس الخليج", "اليوم… العراق والسعودية في نهائي كأس الخليج"),
             ("تقريرنا|| بتوجيه من محافظ ميسان اقامت مديرية التربية مهرجاناً", "بتوجيه من محافظ ميسان أقامت مديرية التربية مهرجاناً"),
             ("اخماد حريق التهم سيارة أجرة في منطقة الشيخ عمر", "إخماد حريق التهم سيارة أجرة في منطقة الشيخ عمر"),
             ("الانواء الجوية تحذر من أمطار غزيرة", "الأنواء الجوية تحذر من أمطار غزيرة"),
             ("وزير الداخلية يصل الى البصرة", "وزير الداخلية يصل إلى البصرة"),
             ("انتهاء الانتخابات وإعلان النتائج", "انتهاء الانتخابات وإعلان النتائج")]
    bad = [(a, proof(a), b) for a, b in tests if proof(a) != b]
    for a, got, want in bad:
        print("FAIL:", a, "\n  got: ", got, "\n  want:", want)
    print("proof ok" if not bad else f"proof {len(bad)} fail")
    raise SystemExit(1 if bad else 0)
