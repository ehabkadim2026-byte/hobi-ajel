"""المدقق اللغوي السريع (قواعد، أقل من ميلي ثانية): يُطبّق على كل عنوان قبل الإرسال — العنوان الأول بالمسار السريع
يُرسل الآن قبل صياغة النموذج (two_stage_all)، فيجب أن يكون نظيفاً من البداية لأن إشعار الهاتف يظهر به.

ما يصلحه (من عيّنة عناوين المسار السريع 05/11):
- علامات الاتجاه الخفية (‏) والتطويل والتشكيل («ذمَّته الماليَّة»، «يبحثٌ»، «المٌتقدم»).
- بادئات القنوات: «اي_نيوز»، «تقريرنا||»، «بالصور..»، «بالفيديو:».
- الهمزات الشائعة بأول الكلمة (اخماد← إخماد، الانواء← الأنواء، اخر← آخر، الى← إلى …) بقاموس مغلق آمن.
- الحروف المكررة خطأً (رياضييين، العراقق، بلاغلات) وفراغ قبل «…».
لا يغيّر المعنى ولا الأسماء: قاموس كلمات كاملة فقط، ولا تخمين.
"""
import re

_DIR = re.compile(r"[‎‏‪-‮⁦-⁩​‌﻿]")
_TASHKEEL = re.compile("[\u064c-\u0652\u0670\u0640]|(?<!\u0627)\u064b(?!\u0627)")  # تنوين الفتح مع الألف («ـاً»/«اً») يبقى
_PREFIX = re.compile(r"^\s*(?:[\w؀-ۿ]+_[\w؀-ۿ]+\s+|تقريرنا\s*\|+\s*|[^:|]{2,18}\|\|\s*|(?:بالصور|بالفيديو|فيديو|صور)\s*(?:\.{2,}|…|:|\|)\s*)")
# كلمات كاملة فقط (حدود عربية)؛ كل مدخل خطأ شائع لا يحتمل معنى آخر بعناوين الأخبار
_FIX = {
    "اخماد": "إخماد", "الانواء": "الأنواء", "انواء": "أنواء", "اخر": "آخر", "الاخير": "الأخير", "الاخيرة": "الأخيرة",
    "الى": "إلى", "الامطار": "الأمطار", "ألامطار": "الأمطار", "الاعلام": "الإعلام", "الاستاذ": "الأستاذ", "الاول": "الأول",
    "الاولى": "الأولى", "اعلن": "أعلن", "اعلنت": "أعلنت", "اكد": "أكد", "اكدت": "أكدت", "اقامت": "أقامت", "اقام": "أقام",
    "امس": "أمس", "الان": "الآن", "اطلاق": "إطلاق", "اجراءات": "إجراءات", "الاجراءات": "الإجراءات", "اصابة": "إصابة",
    "اصابات": "إصابات", "الامن": "الأمن", "الامنية": "الأمنية", "امنية": "أمنية", "الاحد": "الأحد", "الاربعاء": "الأربعاء",
    "انشاء": "إنشاء", "اغلاق": "إغلاق", "افتتاح": "افتتاح", "الانبار": "الأنبار", "الاعظمية": "الأعظمية", "اربيل": "أربيل",
    "ابو": "أبو", "اسعار": "أسعار", "الاسعار": "الأسعار", "اكثر": "أكثر", "اقل": "أقل", "العراقق": "العراق",
    "بلاغلات": "بلاغات", "الاسبوع": "الأسبوع", "الاسبق": "الأسبق", "اعادة": "إعادة", "اضافة": "إضافة", "الغاء": "إلغاء",
    "ايران": "إيران", "الايراني": "الإيراني", "الايرانية": "الإيرانية", "اسرائيل": "إسرائيل", "الاسرائيلي": "الإسرائيلي",
    "الاقليم": "الإقليم", "اقليم": "إقليم", "الامانة": "الأمانة", "امانة": "أمانة", "الاتحادية": "الاتحادية",
}
_FIX_RX = re.compile(r"(?<![؀-ۿ])(" + "|".join(sorted(map(re.escape, _FIX), key=len, reverse=True)) + r")(?![؀-ۿ])")
_TRIPLE = re.compile(r"([؀-ۿ])\1{2,}")  # ثلاثة أحرف متطابقة متتالية لا توجد بالعربية الفصحى


def proof(t):
    if not t:
        return t
    t = _DIR.sub("", t)
    t = _TASHKEEL.sub("", t)
    for _ in range(2):
        t2 = _PREFIX.sub("", t, count=1)
        if t2 == t or len(t2.split()) < 4:
            break
        t = t2
    t = _FIX_RX.sub(lambda m: _FIX[m.group(1)], t)
    t = _TRIPLE.sub(r"\1\1", t)
    t = re.sub(r"(?<![؀-ۿ])رياضيين?ين(?![؀-ۿ])", "رياضيين", t)
    t = re.sub(r"\s+…", "…", t)
    t = re.sub(r"\s+([،:؛.؟!])", r"\1", t)
    t = re.sub(r"\s{2,}", " ", t).strip()
    return t


