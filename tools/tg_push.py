def lead_key(title):
    """الجهة/الشخص المتصدر للعنوان — لسقف المنشورات المتتالية عن الجهة نفسها. أولاً جهة معروفة في أول العنوان، ثم «الجهة: …»، ثم أول كلمتين."""
    from tools.tg_card import split_kicker
