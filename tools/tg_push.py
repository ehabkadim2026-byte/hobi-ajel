    done = {"preview": 0, "photo": 0, "text": 0, "anim": 0, "replies": 0}
    deadline = _t.time() + 60

    def common(p):
        kw = {"parse_mode": "HTML", "disable_notification": "false" if p.get("b") else "true"}
        if p.get("kb"):
            kw["reply_markup"] = p["kb"]
