    from marsad.textnorm import norm_ar
    if not _ACT:
        _ACT.extend(norm_ar(a) for a in ACTORS)
    t = norm_ar(clean_headline(title or ""))
    head = " ".join(t.split()[:6])
    for a in _ACT:
        if a in head:
            return a
    k, _ = split_kicker(t)
    if not k:  # norm_ar يحذف النقطتين: نقرأ «المتحدث:» من العنوان الأصلي
        mk = re.match(r"^\W*([^:«»\d]{2,40}):", clean_headline(title or ""))
